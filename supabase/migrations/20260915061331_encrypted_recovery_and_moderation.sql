-- Anonymous recovery, clarification replies, content reporting, and HR thought moderation.

alter table private.question_threads
  add column if not exists employee_reply text,
  add column if not exists employee_reply_at timestamptz;

create table if not exists private.recovery_vaults (
  vault_hash text primary key check (vault_hash ~ '^[0-9a-f]{64}$'),
  ciphertext text not null check (char_length(ciphertext) between 1 and 200000),
  salt text not null check (char_length(salt) between 16 and 128),
  iv text not null check (char_length(iv) between 12 and 128),
  version integer not null default 1 check (version > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists private.content_reports (
  id bigint generated by default as identity primary key,
  target_type text not null check (target_type in ('question', 'thought')),
  target_id bigint not null,
  question_id bigint not null references public.questions(id) on delete cascade,
  reporter_hash text not null check (reporter_hash ~ '^[0-9a-f]{64}$'),
  reason text not null check (char_length(reason) between 3 and 1000),
  status text not null default 'open' check (status in ('open', 'reviewed', 'dismissed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (target_type, target_id, reporter_hash)
);

create index if not exists content_reports_open_question_idx
  on private.content_reports (question_id, created_at desc)
  where status = 'open';

alter table private.recovery_vaults enable row level security;
alter table private.content_reports enable row level security;

revoke all on private.recovery_vaults from public, anon, authenticated;
revoke all on private.content_reports from public, anon, authenticated;
grant all on private.recovery_vaults to service_role;
grant all on private.content_reports to service_role;

create or replace function public.get_unask_recovery_vault(p_vault_hash text)
returns table (ciphertext text, salt text, iv text, vault_version integer)
language sql
stable
security definer
set search_path = pg_catalog, private, public
as $$
  select rv.ciphertext, rv.salt, rv.iv, rv.version
  from private.recovery_vaults rv
  where public.is_everstage_user()
    and (select auth.uid()) is not null
    and p_vault_hash ~ '^[0-9a-f]{64}$'
    and rv.vault_hash = p_vault_hash;
$$;

create or replace function public.save_unask_recovery_vault(
  p_vault_hash text,
  p_ciphertext text,
  p_salt text,
  p_iv text,
  p_expected_version integer default 0
)
returns table (vault_version integer)
language plpgsql
security definer
set search_path = pg_catalog, private, public
as $$
declare
  v_current integer;
begin
  if not public.is_everstage_user() or (select auth.uid()) is null then
    raise exception 'Verified Everstage access is required';
  end if;
  if p_vault_hash is null or p_vault_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'Invalid recovery vault';
  end if;
  if char_length(coalesce(p_ciphertext, '')) not between 1 and 200000
    or char_length(coalesce(p_salt, '')) not between 16 and 128
    or char_length(coalesce(p_iv, '')) not between 12 and 128 then
    raise exception 'Invalid encrypted recovery payload';
  end if;

  select rv.version into v_current
  from private.recovery_vaults rv
  where rv.vault_hash = p_vault_hash
  for update;

  if not found then
    if coalesce(p_expected_version, 0) <> 0 then
      raise exception 'Recovery vault changed; restore it before saving again';
    end if;
    insert into private.recovery_vaults (vault_hash, ciphertext, salt, iv)
    values (p_vault_hash, p_ciphertext, p_salt, p_iv);
    return query select 1;
    return;
  end if;

  if coalesce(p_expected_version, 0) <> v_current then
    raise exception 'Recovery vault changed; restore it before saving again';
  end if;

  update private.recovery_vaults
  set ciphertext = p_ciphertext,
      salt = p_salt,
      iv = p_iv,
      version = version + 1,
      updated_at = now()
  where vault_hash = p_vault_hash
  returning version into v_current;

  return query select v_current;
end;
$$;

drop function if exists public.get_unask_question_thread(bigint, text);
create function public.get_unask_question_thread(
  p_question_id bigint,
  p_thread_hash text
)
returns table (
  id bigint,
  question text,
  detail text,
  status public.question_status,
  visibility public.question_visibility,
  display_name text,
  upvotes integer,
  dislikes integer,
  comments_count integer,
  responder_label text,
  answer text,
  private_reply text,
  employee_reply text,
  employee_reply_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz
)
language sql
stable
security definer
set search_path = pg_catalog, private, public
as $$
  select q.id, q.question, q.detail, q.status, q.visibility, q.display_name,
    q.upvotes, q.dislikes, q.comments_count, q.responder_label, q.answer,
    t.private_reply, t.employee_reply, t.employee_reply_at, q.created_at, q.updated_at
  from public.questions q
  join private.question_threads t on t.question_id = q.id
  where public.is_everstage_user()
    and (select auth.uid()) is not null
    and q.id = p_question_id
    and p_thread_hash ~ '^[0-9a-f]{64}$'
    and t.token_hash = p_thread_hash;
$$;

create or replace function public.respond_to_unask_clarification(
  p_question_id bigint,
  p_thread_hash text,
  p_reply text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, private, public
as $$
declare
  v_reply text := btrim(coalesce(p_reply, ''));
  v_changed bigint;
begin
  if not public.is_everstage_user() or (select auth.uid()) is null then
    raise exception 'Verified Everstage access is required';
  end if;
  if p_thread_hash is null or p_thread_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'Invalid thread capability';
  end if;
  if char_length(v_reply) not between 1 and 4000 then
    raise exception 'Reply must be between 1 and 4000 characters';
  end if;

  update private.question_threads t
  set employee_reply = v_reply,
      employee_reply_at = now(),
      updated_at = now()
  from public.questions q
  where t.question_id = p_question_id
    and q.id = t.question_id
    and q.status = 'Needs clarification'
    and t.token_hash = p_thread_hash;
  get diagnostics v_changed = row_count;
  if v_changed = 0 then
    raise exception 'Clarification request not found';
  end if;

  update public.questions
  set status = 'Under review', updated_at = now()
  where id = p_question_id;
end;
$$;

create or replace function public.get_unask_hr_thread(p_question_id bigint)
returns table (private_reply text, employee_reply text, employee_reply_at timestamptz)
