create or replace function public.moderate_unask_thought(
  p_thought_id bigint,
  p_action text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, private, public
as $$
declare
  v_question_id bigint;
  v_body text;
begin
  if not public.is_everstage_user()
    or (select auth.uid()) is null
    or private.current_staff_role() <> 'hr' then
    raise exception 'HR access is required';
  end if;
  if p_action not in ('hide', 'publish', 'delete') then
    raise exception 'Invalid moderation action';
  end if;

  select qt.question_id, qt.body into v_question_id, v_body
  from public.question_thoughts qt
  where qt.id = p_thought_id
  for update;
  if not found then
    raise exception 'Thought not found';
  end if;

  if p_action = 'delete' then
    delete from public.question_thoughts where id = p_thought_id;
  else
    update public.question_thoughts
    set status = (case when p_action = 'hide' then 'hidden' else 'published' end)::public.question_thought_status,
        updated_at = now()
    where id = p_thought_id;
  end if;

  insert into private.question_audit_events (question_id, actor_user_id, action, details)
  values (
    v_question_id,
    (select auth.uid()),
    'thought_' || p_action,
    jsonb_build_object('thought_id', p_thought_id, 'body_sha256', encode(extensions.digest(v_body, 'sha256'), 'hex'))
  );
end;
$$;

create or replace function public.submit_unask_report(
  p_target_type text,
  p_target_id bigint,
  p_reason text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, private, public, extensions
as $$
declare
  v_reason text := btrim(coalesce(p_reason, ''));
  v_question_id bigint;
  v_reporter_hash text;
begin
  if not public.is_everstage_user() or (select auth.uid()) is null then
    raise exception 'Verified Everstage access is required';
  end if;
  if p_target_type not in ('question', 'thought') then
    raise exception 'Invalid report target';
  end if;
  if char_length(v_reason) not between 3 and 1000 then
    raise exception 'Report reason must be between 3 and 1000 characters';
  end if;

  if p_target_type = 'question' then
    select q.id into v_question_id
    from public.questions q
    where q.id = p_target_id and q.status in ('Assigned', 'Answered');
  else
    select qt.question_id into v_question_id
    from public.question_thoughts qt
    join public.questions q on q.id = qt.question_id
    where qt.id = p_target_id and qt.status = 'published' and q.status in ('Assigned', 'Answered');
  end if;
  if v_question_id is null then
    raise exception 'Published content not found';
  end if;

  v_reporter_hash := encode(
    extensions.digest((select auth.uid())::text || ':' || p_target_type || ':' || p_target_id::text, 'sha256'),
    'hex'
  );

  insert into private.content_reports (
    target_type, target_id, question_id, reporter_hash, reason
  ) values (
    p_target_type, p_target_id, v_question_id, v_reporter_hash, v_reason
  )
  on conflict (target_type, target_id, reporter_hash)
  do update set reason = excluded.reason, status = 'open', updated_at = now();
end;
$$;

create or replace function public.get_unask_report_counts()
returns table (question_id bigint, open_reports bigint)
language sql
stable
security definer
set search_path = pg_catalog, private, public
as $$
  select cr.question_id, count(*)::bigint
  from private.content_reports cr
  where public.is_everstage_user()
    and (select auth.uid()) is not null
    and private.current_staff_role() = 'hr'
    and cr.status = 'open'
  group by cr.question_id;
$$;

